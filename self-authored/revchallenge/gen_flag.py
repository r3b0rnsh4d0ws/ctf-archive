#!/usr/bin/env python3
"""
gen_flag.py  -  Build-time tool for the "Score Quest" reverse-engineering challenge.

It takes a plaintext flag and encrypts it with a SplitMix64 keystream cipher so that
the flag NEVER exists in plaintext inside the compiled binary. The ciphertext (plus an
obfuscated seed) is written to flag_data.h, which challenge.c includes.

The same SplitMix64 step must be reproduced by challenge.c at runtime to decrypt.

Usage:
    FLAG="CTF{...}" python3 gen_flag.py
"""
import os

# The flag players are trying to recover.
FLAG = os.environ.get("FLAG", "CTF{r3v3rs3_th3_3ncryp73d_sc0r3_m3ch4n1sm_t0_w1n}")

# 64-bit master seed. The compiled binary recovers this at runtime through an
# obfuscated reconstruction (it is never stored as a single obvious constant).
SEED = 0x9A3B2C1D4E5F6071
MASK = 0x123456789ABCDEF0  # used to obfuscate the seed in the header

GOLDEN = 0x9E3779B97F4A7C15


def splitmix64(state: int):
    """Advance the SplitMix64 state and return the next 64-bit output."""
    state = (state + GOLDEN) & 0xFFFFFFFFFFFFFFFF
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & 0xFFFFFFFFFFFFFFFF
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & 0xFFFFFFFFFFFFFFFF
    z = z ^ (z >> 31)
    return state, z


def main():
    data = FLAG.encode("utf-8")
    ct = bytearray()
    # Match challenge.c's recover_seed(): SEED ^ (PI_A + PI_B).
    PI_A = 0x243F6A8885A308D3
    PI_B = 0x13198A2E03707344
    state = (SEED ^ (PI_A + PI_B)) & 0xFFFFFFFFFFFFFFFF
    for i in range(0, len(data), 8):
        state, k = splitmix64(state)
        chunk = data[i:i + 8]
        for j, b in enumerate(chunk):
            ct.append(b ^ ((k >> (8 * j)) & 0xFF))

    seed_xor = SEED ^ MASK

    lines = []
    lines.append("/* Auto-generated by gen_flag.py. DO NOT EDIT. */")
    lines.append("#ifndef FLAG_DATA_H")
    lines.append("#define FLAG_DATA_H")
    lines.append("")
    lines.append("/* The seed is obfuscated: SEED = SEED_XOR ^ SEED_MASK.")
    lines.append("   challenge.c reconstructs it at runtime before decrypting. */")
    lines.append(f"static const unsigned long long SEED_MASK = 0x{MASK:016X}ULL;")
    lines.append(f"static const unsigned long long SEED_XOR = 0x{seed_xor:016X}ULL;")
    lines.append("static const unsigned char ENC_FLAG[] = {")
    for i in range(0, len(ct), 12):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in ct[i:i + 12]) + ",")
    lines.append("};")
    lines.append(f"static const unsigned int ENC_FLAG_LEN = {len(ct)};")
    lines.append("")
    lines.append("#endif /* FLAG_DATA_H */")

    with open("flag_data.h", "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"[+] Wrote flag_data.h ({len(ct)} encrypted bytes).")


if __name__ == "__main__":
    main()
