def arachne_encrypt_block(plaintext, master_key):
    """4-round Feistel network encryption"""
    left = (plaintext >> 32) & 0xFFFFFFFF
    right = plaintext & 0xFFFFFFFF
    
    round_keys = [derive_round_key(master_key, i) for i in range(4)]
    
    for rk in round_keys:
        left, right = feistel_round(left, right, rk)
    
    # Final swap
    return (right << 32) | left

def arachne_decrypt_block(ciphertext, master_key):
    """4-round Feistel network decryption"""
    left = (ciphertext >> 32) & 0xFFFFFFFF
    right = ciphertext & 0xFFFFFFFF
    
    round_keys = [derive_round_key(master_key, i) for i in range(4)]
    
    for rk in reversed(round_keys):
        right, left = feistel_round(right, left, rk)
    
    return (left << 32) | right

