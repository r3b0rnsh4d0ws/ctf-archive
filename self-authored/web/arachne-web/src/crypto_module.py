# Weak LCG parameters (predictable)
LCG_A = 0x5DEECE66D
LCG_C = 0xB
LCG_M = (1 << 48)

def lcg_next(state):
    """Weak LCG - state can be recovered from consecutive outputs"""
    return (LCG_A * state + LCG_C) % LCG_M

def lcg_prev(state):
    """Reverse LCG step"""
    # Modular inverse of A mod M
    a_inv = pow(LCG_A, -1, LCG_M)
    return (a_inv * (state - LCG_C)) % LCG_M

